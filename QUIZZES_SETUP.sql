-- Styloteka v5.3.15: curated board-game quizzes with atomic Stils rewards.
-- Apply ONCE in Supabase SQL Editor before deploying quiz endpoints.
-- The Flask server must use a service_role key; never send it to the browser.

create table if not exists public.styloteka_quiz_questions (
    id bigint generated by default as identity primary key,
    game_id bigint not null references public.games(id) on delete cascade,
    category text not null check (category in ('rules', 'goal', 'strategy', 'tips')),
    question text not null check (length(question) between 12 and 500),
    options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
    correct_index smallint not null check (correct_index between 0 and 3),
    explanation text not null default '',
    source_url text,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    unique (game_id, question)
);

create table if not exists public.styloteka_quiz_attempts (
    telegram_user_id bigint not null,
    question_id bigint not null references public.styloteka_quiz_questions(id) on delete cascade,
    selected_index smallint not null check (selected_index between 0 and 3),
    correct boolean not null,
    reward_stils smallint not null default 0 check (reward_stils between 0 and 2),
    answered_at timestamptz not null default now(),
    primary key (telegram_user_id, question_id)
);

create index if not exists styloteka_quiz_attempts_user_day_idx
    on public.styloteka_quiz_attempts (telegram_user_id, answered_at desc);
create index if not exists styloteka_quiz_questions_game_idx
    on public.styloteka_quiz_questions (game_id, active);

alter table public.styloteka_quiz_questions enable row level security;
alter table public.styloteka_quiz_attempts enable row level security;
revoke all on public.styloteka_quiz_questions from public, anon, authenticated;
revoke all on public.styloteka_quiz_attempts from public, anon, authenticated;
grant select, insert, update, delete on public.styloteka_quiz_questions to service_role;
grant select, insert, update, delete on public.styloteka_quiz_attempts to service_role;
grant usage, select on sequence public.styloteka_quiz_questions_id_seq to service_role;

-- Security invoker + service-role-only EXECUTE; the caller's Telegram identity
-- is validated by Flask BEFORE this function is called.
create or replace function public.styloteka_answer_quiz(
    p_user_id bigint, p_question_id bigint, p_answer_index integer
) returns jsonb
language plpgsql security invoker set search_path = public, pg_temp
as $$
declare
    q public.styloteka_quiz_questions%rowtype;
    total_today integer;
    got_right boolean;
    current_gold integer;
    saved_rows integer;
begin
    if p_user_id is null or p_user_id <= 0 or p_answer_index not between 0 and 3 then
        return jsonb_build_object('status', 'invalid_answer');
    end if;

    -- Serialize claims for the same user: no concurrent double rewards or cap bypass.
    perform pg_advisory_xact_lock(p_user_id);
    select * into q from public.styloteka_quiz_questions
    where id = p_question_id and active = true;
    if not found then return jsonb_build_object('status', 'question_not_found'); end if;

    if exists (select 1 from public.styloteka_quiz_attempts
               where telegram_user_id = p_user_id and question_id = p_question_id) then
        return jsonb_build_object('status', 'already_answered');
    end if;

    select count(*) into total_today from public.styloteka_quiz_attempts
    where telegram_user_id = p_user_id and reward_stils > 0
      and answered_at >= (date_trunc('day', now() at time zone 'Europe/Kyiv') at time zone 'Europe/Kyiv');
    if total_today >= 5 then
        return jsonb_build_object('status', 'daily_limit', 'remaining_today', 0);
    end if;

    got_right := p_answer_index = q.correct_index;
    insert into public.styloteka_quiz_attempts
        (telegram_user_id, question_id, selected_index, correct, reward_stils)
    values (p_user_id, p_question_id, p_answer_index, got_right, case when got_right then 2 else 0 end)
    on conflict do nothing;
    get diagnostics saved_rows = row_count;
    if saved_rows = 0 then return jsonb_build_object('status', 'already_answered'); end if;

    if got_right then
        insert into public.profiles (telegram_user_id, gold)
        values (p_user_id, 2)
        on conflict (telegram_user_id) do update
        set gold = coalesce(public.profiles.gold, 0) + 2
        returning gold into current_gold;
    else
        select coalesce(gold, 0) into current_gold from public.profiles
        where telegram_user_id = p_user_id;
    end if;

    return jsonb_build_object(
        'status', 'answered', 'correct', got_right,
        'correct_index', q.correct_index, 'explanation', q.explanation,
        'reward', case when got_right then 2 else 0 end,
        'remaining_today', 5 - total_today - case when got_right then 1 else 0 end,
        'balance', coalesce(current_gold, 0)
    );
end;
$$;
revoke all on function public.styloteka_answer_quiz(bigint, bigint, integer) from public, anon, authenticated;
grant execute on function public.styloteka_answer_quiz(bigint, bigint, integer) to service_role;

