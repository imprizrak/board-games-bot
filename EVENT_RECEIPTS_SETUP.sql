CREATE OR REPLACE FUNCTION public.styloteka_review_event_receipt(
 p_receipt_id bigint,p_admin_id bigint,p_decision text)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE rec public.event_payment_receipts%ROWTYPE;
        ev public.events%ROWTYPE;
        used_count integer;
BEGIN
  IF p_decision NOT IN ('approved','rejected') THEN
    RETURN jsonb_build_object('error','invalid_decision');
  END IF;
  SELECT * INTO rec FROM public.event_payment_receipts
    WHERE id=p_receipt_id FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('error','receipt_not_found'); END IF;
  SELECT * INTO ev FROM public.events WHERE id=rec.event_id FOR UPDATE;
  IF NOT FOUND OR ev.status <> 'scheduled' OR ev.payment_method <> 'receipt' THEN
    RETURN jsonb_build_object('error','event_closed');
  END IF;
  IF rec.status <> 'pending' THEN
    RETURN jsonb_build_object('error','already_reviewed','status',rec.status);
  END IF;
  IF p_decision='approved' THEN
    IF ev.max_participants IS NOT NULL AND ev.max_participants>0 THEN
      SELECT count(*) INTO used_count FROM public.event_rsvps
      WHERE event_id=rec.event_id AND status='going';
      IF used_count>=ev.max_participants AND NOT EXISTS (
        SELECT 1 FROM public.event_rsvps WHERE event_id=rec.event_id
          AND telegram_user_id=rec.telegram_user_id AND status='going') THEN
        RETURN jsonb_build_object('error','event_full');
      END IF;
    END IF;
    -- Approving and registering are one transaction. No client may create this RSVP.
    UPDATE public.event_rsvps SET status='going',username=rec.username,
      display_name=rec.display_name WHERE event_id=rec.event_id AND
      telegram_user_id=rec.telegram_user_id;
    IF NOT FOUND THEN
      INSERT INTO public.event_rsvps(event_id,username,display_name,telegram_user_id,status)
      VALUES(rec.event_id,rec.username,rec.display_name,rec.telegram_user_id,'going')
      ON CONFLICT(event_id,username) DO UPDATE SET
        status='going',display_name=EXCLUDED.display_name,
        telegram_user_id=EXCLUDED.telegram_user_id;
    END IF;
  END IF;
  UPDATE public.event_payment_receipts SET status=p_decision,
    reviewed_by=p_admin_id,reviewed_at=now(),updated_at=now()
    WHERE id=rec.id;
  RETURN jsonb_build_object('status',p_decision,'event_id',rec.event_id,
    'telegram_user_id',rec.telegram_user_id,'receipt_id',rec.id);
END;$$;
REVOKE ALL ON FUNCTION public.styloteka_review_event_receipt(bigint,bigint,text)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.styloteka_review_event_receipt(bigint,bigint,text) TO service_role;
