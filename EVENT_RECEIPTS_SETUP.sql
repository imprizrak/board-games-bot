  ADD COLUMN IF NOT EXISTS payment_details text NOT NULL DEFAULT '';
UPDATE public.events SET payment_method = 'monobank'
 WHERE price_kop > 0 AND payment_method = 'free';
ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_payment_method_check;
ALTER TABLE public.events ADD CONSTRAINT events_payment_method_check
 CHECK (payment_method IN ('free', 'receipt', 'monobank'));
ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_payment_consistency_check;
ALTER TABLE public.events ADD CONSTRAINT events_payment_consistency_check
 CHECK ((price_kop = 0 AND payment_method = 'free') OR
        (price_kop > 0 AND payment_method IN ('receipt', 'monobank')));

CREATE TABLE IF NOT EXISTS public.event_payment_receipts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE RESTRICT,
  telegram_user_id bigint NOT NULL,
  username text NOT NULL,
  display_name text NOT NULL,
  receipt_path text NOT NULL,
  receipt_mime text NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, telegram_user_id),
  CHECK(length(receipt_path)>3)
);
CREATE INDEX IF NOT EXISTS event_payment_receipts_status_event_idx
 ON public.event_payment_receipts (status,event_id,created_at DESC);
ALTER TABLE public.event_payment_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.event_payment_receipts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.event_payment_receipts TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_payment_receipts_id_seq TO service_role;

