-- Styloteka 5.3.37: private submissions for participant-created events.
-- Safe to apply before deployment. Pending submissions do not appear in public.events.
CREATE TABLE IF NOT EXISTS public.event_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_user_id bigint NOT NULL,
    submitted_by_username text NOT NULL DEFAULT '',
    submitted_by_display_name text NOT NULL DEFAULT '',
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 3 AND 120),
    event_date date NOT NULL,
    event_time text NOT NULL DEFAULT '',
    description text NOT NULL DEFAULT '',
    location_text text NOT NULL DEFAULT '',
    location_map_url text NOT NULL DEFAULT '',
    location_lat double precision,
    location_lng double precision,
    game_name text NOT NULL DEFAULT '',
    game_names jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(game_names) = 'array'),
    max_participants integer NOT NULL DEFAULT 0 CHECK (max_participants BETWEEN 0 AND 99),
    cover_url text,
    price_kop integer NOT NULL DEFAULT 0 CHECK (price_kop BETWEEN 0 AND 100000000),
    payment_method text NOT NULL DEFAULT 'free' CHECK (payment_method IN ('free','receipt','monobank')),
    payment_details text NOT NULL DEFAULT '',
    payment_link text NOT NULL DEFAULT '',
    attendance_reward_stils integer NOT NULL DEFAULT 50 CHECK (attendance_reward_stils BETWEEN 0 AND 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    created_event_id bigint REFERENCES public.events(id) ON DELETE SET NULL,
    reviewed_by bigint,
    reviewed_at timestamptz,
    reject_reason text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((price_kop = 0 AND payment_method = 'free') OR
           (price_kop > 0 AND payment_method IN ('receipt','monobank')))
);
CREATE INDEX IF NOT EXISTS event_submissions_author_status_idx
 ON public.event_submissions(telegram_user_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS event_submissions_review_idx
 ON public.event_submissions(status,created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS event_submissions_created_event_unique
 ON public.event_submissions(created_event_id) WHERE created_event_id IS NOT NULL;
ALTER TABLE public.event_submissions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.event_submissions FROM PUBLIC,anon,authenticated;
GRANT SELECT, INSERT, UPDATE ON public.event_submissions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_submissions_id_seq TO service_role;

-- Atomic, idempotent publishing. The endpoint calling this function must first
-- verify the requesting Telegram user is a group administrator. Direct clients
-- cannot call it (service_role only).
CREATE OR REPLACE FUNCTION public.styloteka_approve_event_submission(
    p_submission_id bigint, p_admin_telegram_user_id bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $fn$
DECLARE
    s public.event_submissions%ROWTYPE;
    new_id bigint;
BEGIN
    IF p_submission_id IS NULL OR p_submission_id <= 0 OR
       p_admin_telegram_user_id IS NULL OR p_admin_telegram_user_id <= 0 THEN
        RETURN jsonb_build_object('status','invalid_request');
    END IF;
    SELECT * INTO s FROM public.event_submissions
    WHERE id = p_submission_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('status','submission_not_found');
    END IF;
    IF s.status <> 'pending' THEN
        RETURN jsonb_build_object('status','submission_already_reviewed');
    END IF;
    IF s.event_date < (now() AT TIME ZONE 'Europe/Kyiv')::date THEN
        RETURN jsonb_build_object('status','event_date_in_past');
    END IF;

    INSERT INTO public.events (
        title, event_date, event_time, description, created_by,
        max_participants, cover_url, status, completed_at,
        game_name, game_names, location_text, location_map_url,
        location_lat, location_lng, price_kop, payment_method,
        payment_details, payment_link, attendance_reward_stils,
        quests_event_url, quests_count, quests_checked_in_count
    ) VALUES (
        s.title, s.event_date, s.event_time, s.description,
        COALESCE(NULLIF(s.submitted_by_display_name,''),s.submitted_by_username),
        s.max_participants, s.cover_url, 'scheduled', NULL,
        s.game_name, s.game_names, s.location_text, s.location_map_url,
        s.location_lat, s.location_lng, s.price_kop, s.payment_method,
        s.payment_details, s.payment_link, s.attendance_reward_stils,
        NULL, 0, 0
    ) RETURNING id INTO new_id;

    UPDATE public.event_submissions
      SET status = 'approved',created_event_id = new_id,
          reviewed_by = p_admin_telegram_user_id,
          reviewed_at = now(),updated_at = now()
    WHERE id = p_submission_id;
    RETURN jsonb_build_object('status','approved','event_id',new_id);
END;
$fn$;
REVOKE ALL ON FUNCTION public.styloteka_approve_event_submission(bigint,bigint)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.styloteka_approve_event_submission(bigint,bigint)
 TO service_role;
